function changeLanguage(lang) {
    // Save preference
    localStorage.setItem('asf-language', lang);
    
    // Update selector
    document.getElementById('languageSelect').value = lang;
    
    // Apply translations
    applyTranslations(lang);
}

function applyTranslations(lang) {
    const dict = translations[lang] || translations['pt-BR'];
    
    // Translate elements with data-i18n attribute
    document.querySelectorAll('[data-i18n]').forEach(element => {
        const key = element.getAttribute('data-i18n');
        if (dict[key]) {
            // Handle input placeholders separately
            if (element.placeholder !== undefined) {
                element.placeholder = dict[key];
            } else if (element.tagName === 'INPUT' && element.type === 'button') {
                element.value = dict[key];
            } else {
                element.textContent = dict[key];
            }
        }
    });
    
    // Translate specific elements by ID or class
    // Header buttons titles
    const darkModeBtn = document.getElementById('darkModeToggle');
    if (darkModeBtn) darkModeBtn.title = dict['darkModeToggle'];
    
    const notifyBtn = document.querySelector('.icon-btn[]');
    if (notifyBtn) notifyBtn.title = dict['notifications'];
    
    const shopCartBtn = document.getElementById('shop-cart-btn');
    if (shopCartBtn) shopCartBtn.title = dict['shopCart'];
    
    const whatsappLink = document.querySelector('a[]');
    if (whatsappLink) whatsappLink.title = dict['whatsapp'];
    
    const campaignBtn = document.querySelector('.icon-btn[]');
    if (campaignBtn) campaignBtn.title = dict['campaignModal'];
    
    const supportBtn = document.querySelector('.icon-btn[title="Apoie o App"]');
    if (supportBtn) supportBtn.title = dict['brandSupport'];
    
    // Translate static text that's harder to target with data-i18n
    // We'll handle this by adding data-i18n attributes to elements in the HTML
}

// Initialize language on page load
document.addEventListener('DOMContentLoaded', function() {
    const savedLang = localStorage.getItem('asf-language') || 'pt-BR';
    changeLanguage(savedLang);
});
